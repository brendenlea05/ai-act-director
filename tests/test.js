const assert = require('node:assert/strict');
const L = require('../engine.js');
const parse = (kind, text) => { const csv=L.parseCSV(text); return L.convert(csv,kind,L.guessMapping(csv.headers,kind)); };
const po='PO Number,SKU,Quantity,Unit Price,Supplier,Currency\nPO-1,A,10,20,Acme,USD\nPO-1,B,5,4,Acme,USD\nPO-2,C,3,11,Acme,USD\n';
const rec='Purchase Order,Item,Received Qty\nPO-1,A,8\nPO-1,B,5\nPO-2,C,3\n';
const inv='PO,SKU,QTY,Price,Invoice Number\nPO-1,A,10,22,INV-9\nPO-1,B,5,4,INV-9\nPO-2,C,3,11,INV-10\n';
const out=L.reconcile({pos:parse('po',po),receipts:parse('receipts',rec),invoices:parse('invoices',inv)});
assert.equal(out.summary.flaggedItems,1);
assert.equal(out.summary.estimate,44);
assert.equal(out.summary.matchedItems,2);
assert.ok(out.issues.some(i=>i.type==='BILLED_OVER_RECEIPT'));
assert.ok(out.issues.some(i=>i.type==='PRICE_ABOVE_PO'));
assert.ok(L.parseCSV('name,desc\n"test, quoted","multi\nline"\n').rows[0].desc.includes('\n'));
assert.equal(L.stringifyCSV([{a:'x,y'}],['a']),'a\r\n"x,y"');
assert.equal(L.stringifyCSV([{a:'=1+1'}],['a']),"a\r\n'=1+1");
assert.equal(L.stringifyCSV([{a:'+SUM(1,2)'}],['a']),"a\r\n\"'+SUM(1,2)\"");
assert.equal(L.stringifyCSV([{a:'-1+2'}],['a']),"a\r\n'-1+2");
assert.equal(L.stringifyCSV([{a:'@SUM(1,2)'}],['a']),"a\r\n\"'@SUM(1,2)\"");
assert.equal(L.stringifyCSV([{a:'\t=1+1'}],['a']),"a\r\n'\t=1+1");
assert.equal(L.stringifyCSV([{a:'\uFEFF=1+1'}],['a']),"a\r\n'\uFEFF=1+1");
assert.equal(L.stringifyCSV([{a:-5}],['a']),"a\r\n-5");

assert.throws(()=>L.parseCSV('a,b\n"not closed,b'),/unclosed/);
assert.throws(()=>L.convert(L.parseCSV('PO,SKU,QTY\na,b,-1'),'receipts',L.guessMapping(['PO','SKU','QTY'],'receipts')),/invalid/);
const dup=L.reconcile({pos:parse('po','po,sku,qty,price\nX,1,10,10'), receipts:parse('receipts','po,sku,qty\nX,1,10'),invoices:parse('invoices','po,sku,qty,price,invoice\nX,1,5,10,Z\nX,1,5,10,Z')});
assert.ok(dup.issues.some(i=>i.type==='POSSIBLE_DUPLICATE_INVOICE_LINE'));
const wrongCurrency=L.reconcile({pos:parse('po','po,sku,qty,price,currency\nX,1,2,10,USD'),receipts:parse('receipts','po,sku,qty\nX,1,2'),invoices:parse('invoices','po,sku,qty,price,invoice,currency\nX,1,2,15,Z,EUR')});
assert.ok(wrongCurrency.issues.some(i=>i.type==='CURRENCY_MISMATCH'));
assert.equal(wrongCurrency.summary.estimate,0);
const noReceipt=L.reconcile({pos:parse('po','po,sku,qty,price\nX,1,2,10'),receipts:parse('receipts','po,sku,qty\nY,2,1'),invoices:parse('invoices','po,sku,qty,price,invoice\nX,1,2,10,Z')});
assert.ok(noReceipt.issues.some(i=>i.type==='NO_RECEIPT_RECORD'));
console.log('PASS: all reconciliation, CSV, duplicate, currency and missing-record tests');
